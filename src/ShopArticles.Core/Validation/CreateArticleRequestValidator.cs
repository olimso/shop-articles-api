using FluentValidation;
using ShopArticles.Core.Contracts;

namespace ShopArticles.Core.Validation;

public class CreateArticleRequestValidator : AbstractValidator<CreateArticleRequest>
{
    public const int NameMaxLength = 64;
    public const int DescriptionMaxLength = 2048;
    public const int CategoryMaxLength = 64;

    public CreateArticleRequestValidator()
    {
        RuleFor(x => x.ArticleId)
            .Null().WithMessage("article_id must not be sent; it is generated by the server.");

        RuleFor(x => x.Name)
            .NotEmpty()
            .MaximumLength(NameMaxLength);

        RuleFor(x => x.Description)
            .NotEmpty()
            .MaximumLength(DescriptionMaxLength);

        RuleFor(x => x.Category)
            .MaximumLength(CategoryMaxLength);

        RuleFor(x => x.Price)
            .NotNull()
            .GreaterThanOrEqualTo(0);

        RuleFor(x => x.Currency)
            .NotEmpty()
            .When(x => x.Price > 0)
            .WithMessage("currency is required when price is greater than 0.");

        RuleFor(x => x.Currency)
            .Must(CurrencyCodes.IsValid)
            .When(x => !string.IsNullOrEmpty(x.Currency))
            .WithMessage("currency must be a valid ISO 4217 code (e.g. NOK, CZK, EUR).");
    }
}
